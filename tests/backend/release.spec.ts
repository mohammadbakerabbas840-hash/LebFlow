import {test, expect} from '@playwright/test';

test('parent creates independent child cases, archives and starts again', async ({page}) => {
  test.setTimeout(120000);
  await page.goto('/#/account');
  await page.locator('main').getByRole('button',{name:'Create account',exact:true}).click();
  const form = page.locator('form').filter({has:page.locator('input[name=confirmPassword]')});
  const email = `family-${Date.now()}@example.com`;
  for (const [name,value] of Object.entries({name:'Sample Parent',nameArabic:'والد تجريبي',email,dob:'1990-01-01',password:'sample-password-123',confirmPassword:'sample-password-123'})) await form.locator(`input[name="${name}"]`).fill(value);
  await form.locator('.consent-label input').check();
  let registered = page.waitForResponse(r => r.url().endsWith('/auth/register'));
  await form.locator('button[type=submit]').click();
  const firstAttempt = await registered;
  if (firstAttempt.status() === 429) {
    await page.waitForTimeout((Number(firstAttempt.headers()['retry-after']) || 60) * 1000 + 1000);
    registered = page.waitForResponse(r => r.url().endsWith('/auth/register'));
    await form.locator('button[type=submit]').click();
    expect((await registered).status()).toBe(201);
  } else expect(firstAttempt.status()).toBe(201);
  await expect(page.getByRole('heading',{name:'Sample Parent',exact:true})).toBeVisible();
  const family = page.locator('section.release-panel').filter({has:page.getByRole('heading',{name:'Family members',exact:true})});
  await family.locator('input[name=name]').fill('Sample Child');
  await family.locator('input[name=name_arabic]').fill('طفل تجريبي');
  await family.locator('input[name=dob]').fill('2026-09-01');
  await family.getByRole('checkbox').check();
  await family.getByRole('button',{name:'Add family member'}).click();
  await expect(family.locator('.family-row')).toContainText('Sample Child');
  await page.goto('/#/services/identity');
  await page.getByRole('button',{name:'Create personal request',exact:true}).click();
  await expect(page.locator('main')).toHaveAttribute('aria-busy','false');
  await page.getByLabel('Applicant',{exact:true}).selectOption({label:'Sample Child'});
  await page.getByRole('button',{name:'Build my checklist'}).click();
  await page.getByRole('combobox',{name:'Applicant’s age group'}).selectOption('child');
  await page.getByRole('combobox',{name:'Submission route confirmed by the office'}).selectOption('mukhtar');
  await expect(page.getByText('Are you a foreign resident in Lebanon?',{exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'Generate checklist',exact:true}).click();
  await page.getByRole('button',{name:'Create personal request',exact:true}).click();
  await expect(page.locator('main')).toHaveAttribute('aria-busy','false');
  const cases = (await (await page.request.get('/api/v1/cases')).json()).data;
  expect(cases).toHaveLength(2);
  expect(cases.find((c:{applicantName:string})=>c.applicantName==='Sample Child').notApplicable).toEqual(['loss','residence']);
  await page.goto('/#/cases');
  await page.locator('.case-card').filter({hasText:'Sample Child'}).click();
  await expect(page.getByLabel('Applicant',{exact:true})).toHaveValue(cases.find((c:{applicantName:string})=>c.applicantName==='Sample Child').familyMemberId);
  await page.getByRole('button',{name:'Archive application',exact:true}).click();
  await page.getByRole('button',{name:'Confirm archive',exact:true}).click();
  await expect.poll(async()=> (await (await page.request.get('/api/v1/cases')).json()).data.length).toBe(1);
  await page.getByLabel('Applicant',{exact:true}).selectOption({label:'Sample Child'});
  await page.getByRole('button',{name:'Create personal request',exact:true}).click();
  await expect.poll(async()=> (await (await page.request.get('/api/v1/cases')).json()).data.length).toBe(2);
  await page.goto('/#/account');
  await page.getByText('Archived applications',{exact:true}).click();
  await expect(page.locator('details').filter({has:page.getByText('Archived applications',{exact:true})})).toContainText('Sample Child');
  const security = page.locator('section.release-panel').filter({has:page.getByRole('heading',{name:'Account security',exact:true})});
  await expect(security.getByRole('checkbox')).toBeDisabled();
  await security.getByLabel('Current password',{exact:true}).fill('sample-password-123');
  await security.getByRole('button',{name:'Set up authenticator'}).click();
  await expect(security.locator('code')).not.toBeEmpty();
  await page.setViewportSize({width:375,height:900});
  for (const locale of ['ar','fr','en']) {
    await page.getByRole('combobox',{name:/Language|اللغة|Langue/}).first().selectOption(locale);
    await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth+1)).toBe(true);
  }
  expect(await page.evaluate(()=>JSON.stringify(localStorage))).not.toContain('Sample Child');
  const currentSession = (await (await page.request.get('/api/v1/security')).json()).data.sessions.find((s:{current:boolean}) => s.current);
  const csrf = (await page.context().cookies()).find(c => c.name === 'XSRF-TOKEN')!;
  expect((await page.request.delete(`/api/v1/security/sessions/${currentSession.id}`, {headers:{'X-XSRF-TOKEN':decodeURIComponent(csrf.value)}})).status()).toBe(200);
  expect((await page.request.get('/api/v1/me')).status()).toBe(401);
});
